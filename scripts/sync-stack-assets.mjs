import { readFileSync, readdirSync, mkdirSync, writeFileSync, cpSync, rmSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
function output(path, content) {
  const target = join(root, path)
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) throw new Error(`Generated asset drift: ${path}`)
  } else {
    mkdirSync(join(target, '..'), { recursive: true })
    writeFileSync(target, content)
  }
}
const runtime = join(root, 'packages/runtime-ai')
const version = JSON.parse(readFileSync(join(runtime, 'package.json'))).version
const cliVersion = JSON.parse(readFileSync(join(root, 'packages/cli/package.json'))).version
const sources = Object.fromEntries(readdirSync(join(runtime, 'src')).sort().map(name => [name, readFileSync(join(runtime, 'src', name), 'utf8')]))
output('packages/cli/src/generated/runtime-ai.ts', `// Generated by scripts/sync-stack-assets.mjs. Edit packages/runtime-ai/src instead.\nexport const cliVersion = ${JSON.stringify(cliVersion)}\nexport const runtimeVersion = ${JSON.stringify(version)}\nexport const runtimeSources: Record<string, string> = ${JSON.stringify(sources, null, 2)}\n`)
output('packages/agent-pack/src/modules/qvac.mdc', `---\ndescription: Local AI session ownership and native adapter boundaries for generated apps.\nalwaysApply: false\n---\n\n# QVAC integration contract\n\nRead the target app's .unstoppable/project.json and installed dependency types first. The compatibility table selects desktop/Node versus experimental Expo. Renderer code uses IPC only; native imports live inside adapters. Upstream docs own detailed SDK APIs: https://docs.qvac.tether.io/sdk/js-ts-sdk/.\n\n${readFileSync(join(runtime, 'README.md'), 'utf8').trimEnd().replace(/^# Unstoppable AI runtime/, '## Local session')}\n`)

const manifest = JSON.parse(readFileSync(join(root, 'packages/cli/src/compatibility/profiles.json')))
for (const profile of Object.values(manifest.profiles)) {
  if (profile.aiRuntime && profile.aiRuntime !== version) throw new Error(`Runtime version mismatch: ${profile.id}`)
}
const lines = ['---', 'description: Generated compatibility profiles for scaffolded apps; use the installed app profile before changing dependencies.', 'alwaysApply: false', '---', '', '# Compatibility profiles', '', 'Generated from `packages/cli/src/compatibility/profiles.json`. Do not edit this table by hand.', '', 'Read each app’s `.unstoppable/project.json`, package.json and lockfile first. These ranges describe a generator profile; they are not a guarantee for every resolved graph. Expo is a separate deferred native target. A profile with the new AI adapter still needs real runtime acceptance.', '', '| Platform | Profile | Maturity | AI runtime | Validation |', '| --- | --- | --- | --- | --- |']
for (const [platform, profile] of Object.entries(manifest.profiles)) {
  lines.push(`| ${platform} | ${profile.id} / revision ${profile.revision} | ${profile.maturity} | ${profile.aiRuntime || 'separate Expo implementation'} | ${profile.validation.adapter} |`)
}
lines.push('')
for (const [platform, profile] of Object.entries(manifest.profiles)) {
  lines.push(`## ${platform}`, '', '| Package | Range | Group |', '| --- | --- | --- |')
  for (const [group, deps] of Object.entries({ base: profile.dependencies, development: profile.devDependencies, ...profile.featureDependencies })) {
    for (const [name, range] of Object.entries(deps)) lines.push(`| ${name} | ${range} | ${group} |`)
  }
  lines.push('')
}
lines.push('For upgrades, run `us compatibility check -o <app>` and review the plan. It reads metadata and files without changing them. Do not regenerate edited apps with `--force`. Compare the installed SDK types and version-matched upstream release notes; keep the coupled Expo/native graph together.', '')
output('packages/agent-pack/src/core/verified-versions.mdc', lines.join('\n'))
output('packages/agent-pack/src/core/compatibility-profiles.json', JSON.stringify(manifest, null, 2) + '\n')

if (!check) {
  const bundled = join(root, 'packages/cli/agent-pack-src')
  rmSync(bundled, { recursive: true, force: true })
  cpSync(join(root, 'packages/agent-pack/src'), bundled, { recursive: true })
}
console.log(check ? 'Generated runtime and compatibility assets match' : 'Synced runtime, compatibility profiles and agent pack')
